/**
 * fetch-devotional-verses.mjs
 *
 * Reads every verse reference from app/data/devotional.js and downloads the
 * verse text from bible-api.com using the World English Bible (WEB), which is
 * in the public domain. The result is written to app/data/devotional-verses.js
 * as `var DEVOTIONAL_VERSES = { "<reference>": "<text>", ... }`.
 *
 * The WEB translation renders the divine name as "Yahweh"; this script
 * rewrites it to "the LORD" for readability.
 *
 * A cache (scripts/.verse-cache.json) keeps re-runs fast and lets the script
 * resume if the network drops halfway through.
 *
 * Usage:  node scripts/fetch-devotional-verses.mjs
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const DEVOTIONAL = join(root, 'app', 'data', 'devotional.js');
const OUT = join(root, 'app', 'data', 'devotional-verses.js');
const CACHE = join(here, '.verse-cache.json');

const API = 'https://bible-api.com/';
const TRANSLATION = 'web';
const CONCURRENCY = 1;
const MAX_TRIES = 6;
const DELAY = 700;

function stripUnbalancedQuotes(s) {
  // WEB text sometimes carries a quotation mark that belongs to a neighbouring
  // verse. Drop an outer quote only when its counterpart is completely absent.
  var pairs = [['\u201c', '\u201d'], ['\u2018', '\u2019'], ['"', '"']];
  for (var i = 0; i < pairs.length; i++) {
    var open = pairs[i][0];
    var close = pairs[i][1];
    var nOpen = (s.match(new RegExp(open, 'g')) || []).length;
    var nClose = (s.match(new RegExp(close, 'g')) || []).length;
    if (s.charAt(0) === open && nClose === 0) s = s.slice(1).trimStart();
    if (s.charAt(s.length - 1) === close && nOpen === 0) s = s.slice(0, -1).trimEnd();
  }
  return s;
}

function normalise(text) {
  return stripUnbalancedQuotes(String(text || '')
    .replace(/\s+/g, ' ')
    .replace(/\bYahweh\b/g, 'the LORD')
    .replace(/\s+([,.;:!?])/g, '$1')
    .trim());
}

async function loadRefs() {
  const src = await readFile(DEVOTIONAL, 'utf8');
  const refs = [];
  const seen = new Set();
  for (const line of src.split('\n')) {
    const m = line.match(/^\s*'(\d+)\|/);
    if (!m) continue;
    const fields = line.trim().replace(/^'|',$/g, '').split('|');
    const ref = fields[3];
    if (ref && !seen.has(ref)) {
      seen.add(ref);
      refs.push(ref);
    }
  }
  return refs;
}

async function loadCache() {
  try {
    return JSON.parse(await readFile(CACHE, 'utf8'));
  } catch {
    return {};
  }
}

async function fetchVerse(ref) {
  const url = API + encodeURIComponent(ref) + '?translation=' + TRANSLATION;
  let lastErr;
  for (let attempt = 1; attempt <= MAX_TRIES; attempt++) {
    try {
      const res = await fetch(url, { headers: { Accept: 'application/json' } });
      if (res.status === 429) {
        const wait = 5000 * attempt;
        await new Promise((r) => setTimeout(r, wait));
        throw new Error('HTTP 429');
      }
      if (!res.ok) throw new Error('HTTP ' + res.status);
      const data = await res.json();
      const text = normalise(data.text);
      if (!text) throw new Error('empty text');
      return text;
    } catch (err) {
      lastErr = err;
      await new Promise((r) => setTimeout(r, 800 * attempt));
    }
  }
  throw new Error('failed: ' + ref + ' (' + lastErr.message + ')');
}

async function run() {
  const refs = await loadRefs();
  const cache = await loadCache();
  const missing = refs.filter((r) => !cache[r]);
  console.log(`References: ${refs.length} total, ${missing.length} to download.`);

  let done = 0;
  let failed = 0;
  const queue = missing.slice();

  async function worker() {
    while (queue.length) {
      const ref = queue.shift();
      try {
        cache[ref] = await fetchVerse(ref);
      } catch (err) {
        failed++;
        console.warn('  ! ' + err.message);
      }
      done++;
      if (done % 25 === 0 || done === missing.length) {
        console.log(`  ${done}/${missing.length} downloaded`);
      }
      await new Promise((r) => setTimeout(r, DELAY));
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  // Keep the output ordered by first appearance in the devotional, and re-run
  // normalisation so verses cached by an older version get tidied too.
  const ordered = {};
  for (const ref of refs) {
    if (cache[ref]) ordered[ref] = normalise(cache[ref]);
  }

  await writeFile(CACHE, JSON.stringify(cache, null, 2) + '\n');

  const banner = [
    '/**',
    ' * Easy English — verse text for the daily devotional.',
    ' *',
    ' * World English Bible (WEB), public domain. The divine name is rendered',
    ' * as "the LORD". Generated by scripts/fetch-devotional-verses.mjs — do not',
    ' * edit by hand.',
    ' */',
    '',
  ].join('\n');

  const body = Object.entries(ordered)
    .map(([ref, text]) => `  ${JSON.stringify(ref)}: ${JSON.stringify(text)},`)
    .join('\n');

  await writeFile(OUT, banner + 'var DEVOTIONAL_VERSES = {\n' + body + '\n};\n');

  console.log(`Wrote ${Object.keys(ordered).length} verses to ${OUT}`);
  if (failed) {
    console.warn(`${failed} verse(s) failed and were left out; re-run to retry.`);
    process.exitCode = 1;
  }
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
